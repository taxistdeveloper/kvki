function Escape-Html([string]$text) {
  if ($null -eq $text) { return '' }
  return [System.Net.WebUtility]::HtmlEncode($text)
}

function Get-ContactLink([string]$value) {
  if ([string]::IsNullOrWhiteSpace($value)) { return 'не указан' }
  $v = $value.Trim()
  $low = $v.ToLowerInvariant()
  if ($low -in @('нет','нету','—')) { return 'не указан' }
  if ($v.Contains('@') -and -not $v.StartsWith('@')) {
    if ($v -match '^[^@\s]+@[^@\s]+\.[^@\s]+$') {
      $enc = Escape-Html $v
      return "<a href=`"mailto:$enc`" class=`"text-sage-600 hover:text-sage-700 font-medium no-translate`" data-no-translate=`"true`">$enc</a>"
    }
  }
  if ($v.StartsWith('@')) {
    $handle = Escape-Html $v.Substring(1)
    $display = Escape-Html $v
    return "<a href=`"https://www.instagram.com/$handle`" class=`"text-sage-600 hover:text-sage-700 font-medium no-translate`" rel=`"noopener noreferrer`" target=`"_blank`" data-no-translate=`"true`">$display</a>"
  }
  if ($v.StartsWith('http://') -or $v.StartsWith('https://')) {
    $enc = Escape-Html $v
    return "<a href=`"$enc`" class=`"text-sage-600 hover:text-sage-700 font-medium no-translate`" rel=`"noopener noreferrer`" target=`"_blank`" data-no-translate=`"true`">$enc</a>"
  }
  if ($v.Contains('.') -and -not $v.Contains(' ')) {
    $url = Escape-Html ("https://$v")
    $display = Escape-Html $v
    return "<a href=`"$url`" class=`"text-sage-600 hover:text-sage-700 font-medium no-translate`" rel=`"noopener noreferrer`" target=`"_blank`" data-no-translate=`"true`">$display</a>"
  }
  return (Escape-Html $v)
}

function Get-PhoneHtml($phones) {
  if ($null -eq $phones -or $phones.Count -eq 0) {
    return '<div class="partner-detail text-sm text-ink-600">Телефон: не указан</div>'
  }
  $links = foreach ($phone in $phones) {
    $digits = ($phone -replace '\D', '')
    $display = Escape-Html $phone
    "<a href=`"tel:$digits`" class=`"text-sage-600 hover:text-sage-700 font-medium no-translate`" data-no-translate=`"true`">$display</a>"
  }
  return "<motion class=`"partner-phone text-sm mt-1`"><span class=`"text-ink-600`">Телефон: </span>$([string]::Join('<br>', $links))</div>"
}

